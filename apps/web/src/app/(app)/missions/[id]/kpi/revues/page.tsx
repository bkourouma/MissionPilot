import Link from "next/link";
import type { Metadata } from "next";
import { FormulaireRevue } from "../../../../../../components/kpi/FormulairesRevueKpi";
import "../../../../../../components/kpi/kpi.css";
import { classesBouton } from "../../../../../../components/ui/Bouton";
import { Carte } from "../../../../../../components/ui/Carte";
import { EtatErreur, EtatVide, PaginationCurseur } from "../../../../../../components/ui/EtatListe";
import { Tableau } from "../../../../../../components/ui/Tableau";
import { chargerServeur } from "../../../../../../lib/api-serveur";
import { formaterDate } from "../../../../../../lib/format";
import { obtenirLangue, obtenirT } from "../../../../../../lib/i18n/serveur";
import { droitsKpi, hrefTableauKpi, lireCurseur } from "../../../../../../lib/kpi";
import {
  cheminRevues,
  hrefRevue,
  hrefRevues,
  libelleStatutRevue,
  type PageRevues,
} from "../../../../../../lib/kpi-pilotage";
import { chargerOptionsPilotage } from "../../../../../../lib/kpi-pilotage-serveur";
import { chargerMission } from "../../../../../../lib/missions-serveur";
import { aujourdhui } from "../../../../../../lib/periode";
import { exigerPermission } from "../../../../../../lib/session";

export async function generateMetadata(): Promise<Metadata> {
  const t = await obtenirT();
  return { title: t("Revues de performance", "Performance reviews") };
}

/**
 * Revues de performance de la mission (KPI-17) : une revue se prépare (ordre du jour proposé par
 * le moteur), se tient (le dossier examiné est figé) puis se clôture quand toutes ses décisions
 * et actions sont terminées ou abandonnées.
 */
export default async function PageRevuesKpi({
  params,
  searchParams,
}: {
  params: Promise<{ id: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const { id } = await params;
  const { utilisateur } = await exigerPermission("kpi.lire");
  const t = await obtenirT();
  const langue = await obtenirLangue();
  const r = await chargerMission(id);
  if (!r.ok) return null;
  const m = r.donnees;
  const curseur = lireCurseur((await searchParams).curseur);
  const droits = droitsKpi(utilisateur.roles, utilisateur.id, m);
  const [revues, options] = await Promise.all([
    chargerServeur<PageRevues>(
      cheminRevues(m.id, `limite=25${curseur ? `&curseur=${encodeURIComponent(curseur)}` : ""}`),
    ),
    chargerOptionsPilotage(utilisateur.roles, m, m.id, langue),
  ]);
  return (
    <div className="mp-kpi">
      <div className="mp-actions-formulaire">
        <Link href={hrefTableauKpi(m.id)} className={classesBouton("secondaire")}>
          {t("Revenir au tableau de bord", "Back to the dashboard")}
        </Link>
      </div>
      <p className="mp-texte-doux">
        {t(
          "Le dossier et la présentation d'une revue sont générés par CabinetPilot à partir des mesures, des alertes et des actions ; les décisions prises sont suivies jusqu'à leur exécution.",
          "The file and presentation of a review are generated by CabinetPilot from the measurements, alerts and actions; the decisions taken are followed until they are executed.",
        )}
      </p>
      {!revues.ok ? (
        <EtatErreur
          titre={t("Les revues n'ont pas pu être chargées.", "The reviews could not be loaded.")}
          message={revues.message}
          hrefReessayer={hrefRevues(m.id)}
        />
      ) : revues.donnees.elements.length === 0 ? (
        <EtatVide
          titre={t("Aucune revue de performance.", "No performance review.")}
          icone="calendrier"
        >
          <p>
            {droits.gerer
              ? t("Planifiez la première revue ci-dessous.", "Schedule the first review below.")
              : t(
                  "Le directeur ou le chef de mission planifie les revues.",
                  "The engagement director or manager schedules the reviews.",
                )}
          </p>
        </EtatVide>
      ) : (
        <>
          <Tableau
            legende={t(
              "Revues de performance de la mission",
              "The engagement's performance reviews",
            )}
            colonnes={[
              { cle: "numero", entete: t("N°", "No."), alignement: "droite" },
              {
                cle: "titre",
                entete: t("Revue", "Review"),
                rendu: (x) => <Link href={hrefRevue(m.id, x.id)}>{x.titre}</Link>,
              },
              {
                cle: "date",
                entete: t("Date", "Date"),
                rendu: (x) => formaterDate(x.date_prevue, "UTC", langue),
              },
              {
                cle: "arrete",
                entete: t("Arrêté des KPI", "KPI cut-off"),
                rendu: (x) => formaterDate(x.date_reference, "UTC", langue),
              },
              {
                cle: "statut",
                entete: t("Statut", "Status"),
                rendu: (x) => libelleStatutRevue(x.statut, langue),
              },
              { cle: "animateur_nom", entete: t("Animateur", "Facilitator") },
            ]}
            lignes={revues.donnees.elements}
            cleLigne={(x) => x.id}
          />
          <PaginationCurseur
            hrefSuivante={
              revues.donnees.curseur_suivant
                ? `${hrefRevues(m.id)}?curseur=${encodeURIComponent(revues.donnees.curseur_suivant)}`
                : null
            }
            hrefDebut={curseur ? hrefRevues(m.id) : null}
          />
        </>
      )}
      {droits.gerer ? (
        <Carte titre={t("Planifier une revue", "Schedule a review")}>
          <FormulaireRevue missionId={m.id} personnes={options.personnes} jour={aujourdhui()} />
        </Carte>
      ) : null}
    </div>
  );
}
